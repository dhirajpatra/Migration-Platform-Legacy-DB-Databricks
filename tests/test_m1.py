# ---------------------------------------------------------------- verifier
class FakeRealClient(DatabricksClient):
    """Non-mock client whose warehouse 'succeeds' except for statements mentioning fn_ordertotal (function not created yet)."""
    def __init__(self):
        super().__init__("https://adb-1.azuredatabricks.net", "dapi1234", "wh1", "migration_dev")
        self.log = []
    def execute(self, sql):
        self.log.append(sql)
        self.calls.append({"statement": sql})
        if "fn_ordertotal" in sql:
            return {"status": "FAILED", "error": "FUNCTION_NOT_FOUND"}
        return {"status": "SUCCEEDED", "rows": []}


def test_real_mode_compiles_in_sandbox_catalog_only(tmp_path):
    db = FakeRealClient()
    g, conf = _to_gate2(tmp_path, db)
    out = _finish(g, conf)
    assert out["verification"]["mode"] == "real" and out["verification"]["executed_in_sandbox"] > 0
    assert all("migration_dev." not in s.replace("migration_dev_sandbox.", "") for s in db.log)   # nothing touches the real catalog
    assert any(s.startswith("CREATE SCHEMA IF NOT EXISTS migration_dev_sandbox.") for s in db.log)
    rep = {e["object_id"]: e for e in json.loads((tmp_path / "target" / "translation_report.json").read_text())["entries"]}
    assert rep["mssql_demo.dbo.vw_openorders"]["status"] == "compile_verified"
    assert rep["mssql_demo.dbo.customers"]["status"] == "compile_verified"
    blocked = rep["mssql_demo.dbo.vw_customerorders"]
    assert blocked["status"] == "needs_review"                                       # human-flagged object is never promoted
    assert blocked["compiled"] is False and "FUNCTION_NOT_FOUND" in blocked["compile_error"]
    assert not any(e["status"] == "auto_verified" for e in rep.values())             # reserved for data-parity (M3)


