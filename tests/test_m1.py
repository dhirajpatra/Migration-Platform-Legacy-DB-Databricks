import json
import pytest
from langgraph.types import Command
from fake_connector import SeedConnector
from migcore.cloud.databricks import DatabricksClient
from migcore.orchestrator.graph import build_graph
from migcore.rules.type_maps import map_type

CFG = {"graph": {"enabled": False}, "engagement": {"target": {"catalog": "migration_dev"}},
       "sources": [{"id": "mssql_demo", "engine": "sqlserver"}, {"id": "oracle_demo", "engine": "oracle"}]}


def col(t, **kw):
    return {"name": "c", "type": t, "length": None, "precision": None, "scale": None, **kw}


# ---------------------------------------------------------------- type rules
@pytest.mark.parametrize("engine,c,expected,flag", [
    ("sqlserver", col("tinyint"), "SMALLINT", "TINYINT_WIDENED"),          # 0-255 does not fit signed TINYINT
    ("sqlserver", col("money"), "DECIMAL(19,4)", None),
    ("sqlserver", col("datetimeoffset"), "TIMESTAMP", "OFFSET_DROPPED"),
    ("sqlserver", col("hierarchyid"), "STRING", "UNMAPPED_TYPE"),
    ("sqlserver", col("decimal", precision=40, scale=2), "DECIMAL(38,2)", "DECIMAL_PRECISION_GT_38"),
    ("oracle", col("NUMBER", precision=10, scale=0), "BIGINT", None),
    ("oracle", col("NUMBER", precision=5, scale=0), "INT", None),
    ("oracle", col("NUMBER", precision=12, scale=2), "DECIMAL(12,2)", None),
    ("oracle", col("NUMBER"), "DECIMAL(38,10)", "NUMBER_NO_PRECISION"),
    ("oracle", col("DATE"), "TIMESTAMP", "ORACLE_DATE_HAS_TIME"),          # Oracle DATE has a time part
    ("oracle", col("VARCHAR2"), "STRING", "EMPTY_STRING_IS_NULL"),
    ("oracle", col("SDO_GEOMETRY"), "STRING", "UNMAPPED_TYPE"),
])
def test_type_rules(engine, c, expected, flag):
    typ, flags = map_type(engine, c)
    assert typ == expected
    assert (flag in {f["code"] for f in flags}) if flag else not any(f["severity"] == "high" for f in flags)


# ---------------------------------------------------------------- end-to-end M1
def _to_gate2(tmp_path, db=None, cfg=CFG):
    g = build_graph(cfg, lambda s: SeedConnector(s["id"], s), databricks=db)
    conf = {"configurable": {"thread_id": "m1"}}
    g.invoke({"run_id": "m1", "run_dir": str(tmp_path), "status": "running", "issues": []}, conf)
    g.invoke(Command(resume={"approved": True, "approver": "lead"}), conf)
    assert g.get_state(conf).next == ("gate2",)
    return g, conf


def _finish(g, conf):
    return g.invoke(Command(resume={"approved": True, "approver": "architect"}), conf)


def test_gate2_rejection_stops_before_translation(tmp_path):
    g, conf = _to_gate2(tmp_path)
    out = g.invoke(Command(resume={"approved": False, "approver": "architect"}), conf)
    assert out["status"] == "g2_rejected" and not (tmp_path / "target" / "ddl").exists()
    assert (tmp_path / "target" / "design.json").exists()                  # the proposal is kept for rework


def test_translation_outputs_and_statuses_in_mock_mode(tmp_path):
    g, conf = _to_gate2(tmp_path)
    out = _finish(g, conf)
    t = tmp_path / "target"
    v = out["verification"]
    assert out["status"] == "m1_done" and v["mode"] == "mock" and v["failed"] == 0 and v["executed_in_sandbox"] == 0
    rep = {e["object_id"]: e for e in json.loads((t / "translation_report.json").read_text())["entries"]}
    # mock mode may prove syntax, never compilation
    assert not any(e["status"] in ("compile_verified", "auto_verified") for e in rep.values())
    cust = (t / "ddl/tables/mssql_demo.dbo.customers.sql").read_text()
    assert "CustomerId BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY" in cust       # identity widened + loadable
    assert "CLUSTER BY (CustomerId)" in cust                                           # 2.5M-row table
    assert "CLUSTER BY" not in (t / "ddl/tables/mssql_demo.dbo.orders.sql").read_text()
    assert rep["mssql_demo.dbo.customers"]["status"] == "syntax_verified"
    led = rep["oracle_demo.demo.ledger"]                                               # NUMBER with no precision
    assert led["status"] == "needs_review" and any(f["code"] == "NUMBER_NO_PRECISION" for f in led["flags"])
    cons = (t / "ddl/constraints.sql").read_text()
    assert "PRIMARY KEY (CustomerId)" in cons and "FOREIGN KEY (CustomerId) REFERENCES migration_dev.mssql_demo_dbo.customers (CustomerId)" in cons
    assert "fk_orders_fk_" not in cons                                                 # no doubled prefix


def test_views_clean_blocked_and_unsafe(tmp_path):
    g, conf = _to_gate2(tmp_path)
    _finish(g, conf)
    t = tmp_path / "target"
    rep = {e["object_id"]: e for e in json.loads((t / "translation_report.json").read_text())["entries"]}
    ok = rep["mssql_demo.dbo.vw_openorders"]
    assert ok["status"] == "syntax_verified"
    sql = (t / ok["artifact"]).read_text()
    body = sql.split("\n", 1)[1].replace("mssql_demo_dbo.", "")                         # skip the provenance comment
    assert "migration_dev.mssql_demo_dbo.orders AS o" in sql and "dbo." not in body    # every reference rewritten to Unity Catalog
    udf = rep["mssql_demo.dbo.vw_customerorders"]
    assert udf["status"] == "needs_review" and udf["blocked_on"] == ["mssql_demo.dbo.fn_ordertotal"]
    assert "migration_dev.mssql_demo_dbo.fn_ordertotal(" in (t / udf["artifact"]).read_text()
    assert any("NOLOCK" in n for n in udf["behaviour_changes"])                         # dropped hint is disclosed, not silent
    # Oracle (+) join: generic transpile silently yields an INNER join, so NO deployable artifact is produced
    plus = rep["oracle_demo.demo.vw_customer_orders"]
    assert plus["status"] == "manual_required" and plus["artifact"] is None
    assert plus["flags"][0]["code"] == "BLOCKED_OUTER_JOIN_PLUS"
    assert not (t / "views" / "oracle_demo.demo.vw_customer_orders.sql").exists()


def test_design_proposal(tmp_path):
    g, conf = _to_gate2(tmp_path)
