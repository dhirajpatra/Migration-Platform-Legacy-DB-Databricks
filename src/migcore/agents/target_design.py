"""Target Designer: proposes naming, layout and per-table decisions. A human approves it at Gate 2."""
from __future__ import annotations
import re

LARGE_TABLE_ROWS = 1_000_000


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9_]", "_", s.lower())


def build_design(cfg: dict, inventories: list[dict]) -> dict:
    t = (cfg.get("engagement", {}) or {}).get("target", {}) or {}
    catalog = t.get("catalog", "migration_dev")
    d = {"catalog": catalog, "sandbox_catalog": t.get("sandbox_catalog", f"{catalog}_sandbox"),
         "layout": {"bronze": "bronze_<source>.<schema>_<table>   (raw landed copy, see cloud module)",
                    "silver": "<source>_<schema>.<table>   (conformed tables, views, functions)"},
         "tables": {}, "views": {}, "callables": {}, "decisions": []}
    for inv in inventories:
        sid = inv["source_id"]
        for tb in inv["tables"]:
            fqn = f"{sid}.{tb['schema']}.{tb['name']}".lower()
            rows = tb.get("row_estimate") or 0
            pk = tb.get("pk") or []
            d["tables"][fqn] = {"source": fqn, "target": f"{catalog}.{slug(sid)}_{slug(tb['schema'])}.{slug(tb['name'])}",
                                "cluster_by": pk[:1] if rows >= LARGE_TABLE_ROWS and pk else [],
                                "row_estimate": rows, "managed": True}
        for o in inv["objects"]:
            tgt = f"{catalog}.{slug(sid)}_{slug(o['schema'])}.{slug(o['name'])}"
            if o["kind"] == "VIEW":
                d["views"][o["id"]] = {"source": o["id"], "target": tgt}
            elif o["kind"] in ("PROCEDURE", "FUNCTION", "PACKAGE"):
                d["callables"][o["id"]] = {"source": o["id"], "target": tgt, "kind": o["kind"]}
    d["decisions"] = [
        "Silver schema per source+schema (`<source>_<schema>`) so multiple sources never collide.",
        "All tables are Unity Catalog managed Delta tables; bronze (raw) and silver (conformed) are separate layers.",
        f"Liquid clustering on the first PK column only for tables >= {LARGE_TABLE_ROWS:,} rows (estimate).",
        "Primary/foreign keys are created as informational constraints (Delta does not enforce them) - integrity is checked by validation tests.",
        "Column defaults are not carried over in this milestone (not extracted); load/ETL logic must supply them.",
        "Identity columns become BIGINT GENERATED BY DEFAULT AS IDENTITY so existing key values can be loaded as-is.",
    ]
    return d
