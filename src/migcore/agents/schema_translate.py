"""Schema Translation agent: tables, identity, PK/FK -> Delta / Unity Catalog DDL (deterministic; no LLM)."""
from __future__ import annotations
import re
from migcore.rules.type_maps import map_type

RESERVED = {"all", "and", "any", "as", "both", "case", "cast", "check", "column", "constraint", "create", "distinct", "else", "end",
            "except", "false", "fetch", "for", "foreign", "from", "full", "grant", "group", "having", "in", "inner", "into", "is",
            "join", "left", "not", "null", "on", "only", "or", "order", "outer", "primary", "references", "right", "select", "some",
            "table", "then", "to", "union", "unique", "user", "using", "when", "where", "with"}
SEV = ["low", "medium", "high"]


def ident(name: str) -> str:
    return name if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) and name.lower() not in RESERVED else f"`{name}`"


def translate_tables(design: dict, inventories: list[dict]) -> tuple[list[dict], dict[str, str], str]:
    """-> (report entries, {relative_path: sql}, constraints_sql)"""
    entries, files, cons = [], {}, ["-- Informational constraints (Delta does not enforce them; validation tests do)."]
    for inv in inventories:
        eng, sid = inv["engine"], inv["source_id"]
        for tb in inv["tables"]:
            fqn = f"{sid}.{tb['schema']}.{tb['name']}".lower()
            d = design["tables"][fqn]
            target, flags, lines, rules = d["target"], [], [], {f"type_map:{eng}"}
            for c in tb["columns"]:
                typ, f = map_type(eng, c)
                flags += [{**x, "column": c["name"]} for x in f]
                line = f"  {ident(c['name'])} {typ}"
                if c.get("identity"):
                    if typ in ("INT", "SMALLINT", "BIGINT"):
                        if typ != "BIGINT":
                            flags.append({"code": "IDENTITY_WIDENED", "severity": "low", "column": c["name"],
                                          "detail": f"identity {typ} widened to BIGINT (Databricks identity columns must be BIGINT)"})
                        line = f"  {ident(c['name'])} BIGINT"
                        rules.add("identity_by_default")
                    else:
                        flags.append({"code": "IDENTITY_UNSUPPORTED_TYPE", "severity": "high", "column": c["name"],
                                      "detail": f"identity on {typ} cannot be expressed; sequence/surrogate redesign needed"})
                if not c.get("nullable", True):
                    line += " NOT NULL"
                if c.get("identity") and typ in ("INT", "SMALLINT", "BIGINT"):
                    line += " GENERATED BY DEFAULT AS IDENTITY"
                lines.append(line)
            cluster = f"\nCLUSTER BY ({', '.join(ident(x) for x in d['cluster_by'])})" if d["cluster_by"] else ""
            if cluster:
                rules.add("liquid_clustering")
            sql = f"CREATE TABLE IF NOT EXISTS {target} (\n" + ",\n".join(lines) + f"\n) USING DELTA{cluster};\n"
            rel = f"ddl/tables/{sid}.{tb['schema']}.{tb['name']}.sql".lower()
            files[rel] = sql
            if tb.get("pk"):
                cons.append(f"ALTER TABLE {target} ADD CONSTRAINT pk_{target.rsplit('.', 1)[1]} PRIMARY KEY ({', '.join(ident(x) for x in tb['pk'])});")
            high = any(x["severity"] == "high" for x in flags)
            entries.append({"object_id": fqn, "kind": "TABLE", "target": target, "status": "needs_review" if high else "translated",
                            "flags": flags, "rules_applied": sorted(rules), "artifact": rel,
                            "behaviour_changes": [x["detail"] for x in flags if x["severity"] in ("medium", "high")],
                            "blocked_on": []})
        for fk in inv["foreign_keys"]:
            child = f"{sid}.{fk['schema']}.{fk['table']}".lower()
            parent = f"{sid}.{fk['ref_schema']}.{fk['ref_table']}".lower()
            if not fk.get("columns") or not fk.get("ref_columns"):
                entries.append({"object_id": f"{child}#{fk['name']}".lower(), "kind": "FOREIGN_KEY", "target": None, "status": "needs_review",
                                "flags": [{"code": "FK_COLUMNS_UNKNOWN", "severity": "medium", "detail": "connector returned no column list"}],
                                "rules_applied": [], "artifact": None, "behaviour_changes": [], "blocked_on": []})
                continue
            ct, pt = design["tables"][child]["target"], design["tables"][parent]["target"]
            nm = re.sub(r"[^a-z0-9_]", "_", fk["name"].lower())
            cname = nm if nm.startswith("fk_") else f"fk_{ct.rsplit('.', 1)[1]}_{nm}"
            cons.append(f"ALTER TABLE {ct} ADD CONSTRAINT {cname} "
                        f"FOREIGN KEY ({', '.join(ident(x) for x in fk['columns'])}) REFERENCES {pt} ({', '.join(ident(x) for x in fk['ref_columns'])});")
    return entries, files, "\n".join(cons) + "\n"
